// Rebuild the static paper after editing data/minotaurs-lament.html.
// KaTeX emits visual HTML and accessible MathML; no browser JS is required.
const fs = require('node:fs');
const path = require('node:path');
const katex = require('katex');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'data/minotaurs-lament.html'), 'utf8');
const rendered = source.replace(/\\\[([\s\S]*?)\\\]|\\\(([\s\S]*?)\\\)/g, (_, display, inline) =>
    katex.renderToString(display ?? inline, {
        displayMode: display !== undefined,
        output: 'htmlAndMathml',
        throwOnError: true,
        strict: 'error',
        trust: false
    })
);
fs.writeFileSync(path.join(root, 'writings/minotaurs-lament.html'), '<!-- Generated by npm run render:paper. Edit data/minotaurs-lament.html. -->\n' + rendered);
const vendor = path.join(root, 'assets/vendor/katex');
const dist = path.dirname(require.resolve('katex'));
fs.mkdirSync(path.join(vendor, 'fonts'), { recursive: true });
fs.copyFileSync(path.join(dist, 'katex.min.css'), path.join(vendor, 'katex.min.css'));
fs.copyFileSync(path.join(dist, '../LICENSE'), path.join(vendor, 'LICENSE'));
for (const file of fs.readdirSync(path.join(dist, 'fonts'))) {
    fs.copyFileSync(path.join(dist, 'fonts', file), path.join(vendor, 'fonts', file));
}
console.log('Rendered paper with local KaTeX CSS, fonts, and accessible MathML.');
